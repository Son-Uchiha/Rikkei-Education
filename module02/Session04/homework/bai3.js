// 1. Tạo một mảng rỗng tên là students
let students = [];

// 2. Sử dụng push() để thêm 3 tên sinh viên vào cuối mảng
students.push("An", "Bình", "Cường");

// 3. Sử dụng unshift() để thêm 1 tên sinh viên vào đầu mảng
students.unshift("Hoàng");

// 4. Sử dụng pop() để xóa sinh viên cuối cùng và in mảng hiện tại ra Console
students.pop();

console.log("Danh sách sinh viên hiện tại:", students);
